/**
 * Generates the example projects in examples/ (one per first-class workflow),
 * plus the synthetic demo recordings and MIDI files in examples/media/.
 *
 *   npm run examples
 */
import { mkdirSync, rmSync, writeFileSync, existsSync } from 'fs';
import { join } from 'path';
import { EXAMPLES, demoMidiFile } from '../src/core/demo/examples';
import { DEMO_VOICES, demoVoice } from '../src/core/demo/synthVoice';
import { encodeWav } from '../src/core/audio/wav';
import { serializeProject, PROJECT_FILE, AUDIO_DIR } from '../src/core/project/project';
import { exportMixFile } from '../src/core/project/exporters';
import { DEMO_BEATS, demoBeatFile } from '../src/core/demo/beats';

const root = join(process.cwd(), 'examples');
mkdirSync(root, { recursive: true });
const media = join(root, 'media');
mkdirSync(media, { recursive: true });

for (const key of Object.keys(DEMO_VOICES)) writeFileSync(join(media, `${key}.wav`), encodeWav(demoVoice(key), 16));
writeFileSync(join(media, 'garage-riff.mid'), demoMidiFile());
for (const key of Object.keys(DEMO_BEATS)) writeFileSync(join(media, `beat-${key}.mid`), demoBeatFile(key));

const lines: string[] = [];
for (const [key, ex] of Object.entries(EXAMPLES)) {
  const p = ex.build();
  const dir = join(root, `${ex.title.replace(/^[A-Z] · /, '').replace(/[^\w\- ]+/g, '').trim()}.vcs`);
  if (existsSync(dir)) rmSync(dir, { recursive: true });
  mkdirSync(join(dir, AUDIO_DIR), { recursive: true });
  for (const s of p.doc.sources) writeFileSync(join(dir, AUDIO_DIR, s.assetName), p.assets.get(s.assetName)!);
  writeFileSync(join(dir, PROJECT_FILE), serializeProject(p.doc));
  // a rendered preview so the result can be heard without opening the app
  const mix = exportMixFile(p.doc, p.audio, { ...p.doc.exportSettings, bitDepth: 16, sampleRate: 32000 });
  writeFileSync(join(dir, `preview_${key}.wav`), mix.bytes);
  lines.push(`- **${ex.title}** – \`${dir.split('/').pop()}\` – ${ex.workflow} (${p.doc.sequence.events.length} events, ${p.doc.sequence.tracks.length} layers, peak ${(20 * Math.log10(mix.result.peak)).toFixed(1)} dBFS)`);
  console.log(`✓ ${ex.title}`);
}
writeFileSync(
  join(root, 'README.md'),
  `# Example projects\n\nGenerated by \`npm run examples\` from synthetic, formant-synthesised vocal-like recordings (no real voices are included).\nOpen a \`.vcs\` folder with **Project ▸ Open…** in the desktop app, or load the same examples from **Project ▸ Example projects** (they are rebuilt in memory).\nEach folder also contains \`preview_*.wav\`, an offline render of its arrangement (32 kHz / 16-bit to keep the repository small).\n\n${lines.join('\n')}\n\n## media/\n\n${Object.entries(DEMO_VOICES).map(([k, v]) => `- \`${k}.wav\` – ${v.description}`).join('\n')}\n- \`garage-riff.mid\` – an 8-bar 2-step style MIDI riff for the MIDI-guided workflow.\n${Object.entries(DEMO_BEATS).map(([k, b]) => `- \`beat-${k}.mid\` – demo beat for Beat Fit: ${b.title}`).join('\n')}\n`,
);
